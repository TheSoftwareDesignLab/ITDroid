package uniandes.tsdl.itdroid.helper;

import java.io.File;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.Collections;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * One pass over the app's smali: every string literal ({@code const-string}) with the class, method
 * and line it is in, and what the code does with it. The detector, the inventory and the patcher
 * all work from this list, so the smali is read once and they agree on what is where.
 *
 * <p>What a literal is used for is found by following its register inside the method to the first
 * instruction that consumes it; a text appended to a {@code StringBuilder} is followed through the
 * builder's {@code toString()} to wherever the whole sentence goes. The consumer is then classified
 * with {@link ConsumerRules}. The method is read forward: a {@code goto} is followed, a conditional
 * branch is not, which is enough for the straight-line code compilers emit around a literal.
 */
public final class SmaliScan {

    /** What becomes of a literal. */
    public enum Consumer {
        UI("ui", "shown to the user"),
        COMPOSABLE("composable", "passed to a composable function"),
        LOG("log", "log message"),
        EXCEPTION("exception", "exception message"),
        DATA("data", "used as data (key, query, pattern, comparison)"),
        COMPILER("compiler", "string generated by the compiler"),
        CONCATENATION("concatenation", "part of a text whose destination is not known"),
        APP_CALL("app-call", "passed to a method of the app"),
        LIBRARY_CALL("library-call", "passed to a library method the rules do not know"),
        FIELD("field", "stored in a field"),
        RETURN("return", "returned by the method"),
        ARRAY("array", "stored in an array"),
        UNUSED("unused", "no consumer found");

        public final String label;
        public final String description;

        Consumer(String label, String description) {
            this.label = label;
            this.description = description;
        }

        /** True for the uses that never put the text in front of the user. */
        public boolean neverShown() {
            return this == LOG || this == EXCEPTION || this == DATA || this == COMPILER;
        }
    }

    /** One {@code const-string} instruction. */
    public static final class Occurrence {
        /** Path relative to the decoded folder, with forward slashes: smali_classes2/com/x/Foo.smali. */
        public final String file;
        /** 1-based line of the instruction. */
        public final int line;
        /** Dotted class name, inner classes with {@code $}: com.x.Foo$1. */
        public final String className;
        public final String method;
        public final String register;
        /** The literal, decoded. */
        public final String text;
        public final Consumer consumer;
        /** The callee or field that consumes it ({@code Landroid/widget/TextView;->setText}); "" when none. */
        public final String via;
        /** Position in the scan (dex folder, file, line): sorting by it gives the order of the code. */
        public final int order;

        Occurrence(String file, int line, String className, String method, String register, String text, Consumer consumer,
                String via, int order) {
            this.file = file;
            this.line = line;
            this.className = className;
            this.method = method;
            this.register = register;
            this.text = text;
            this.consumer = consumer;
            this.via = via;
            this.order = order;
        }

        public String origin() {
            return file + ":" + line;
        }
    }

    private static final Pattern CONST_STRING = Pattern.compile("^const-string(?:/jumbo)?\\s+([vp]\\d+),\\s*\"(.*)\"$");
    private static final Pattern INVOKE = Pattern.compile("^invoke-[a-z-]+(/range)?\\s*\\{([^}]*)\\},\\s*(\\S+)$");
    private static final Pattern FILLED_ARRAY = Pattern.compile("^filled-new-array(/range)?\\s*\\{([^}]*)\\}");
    private static final Pattern OPERANDS = Pattern.compile("^([a-z0-9/-]+)\\s+([vp]\\d+)\\b(?:,\\s*([vp]\\d+)\\b)?");
    private static final Pattern RANGE = Pattern.compile("([vp])(\\d+)\\s*\\.\\.\\s*([vp])(\\d+)");

    /** Instructions followed from a literal before giving up on finding its consumer. */
    private static final int MAX_STEPS = 200;
    private static final Pattern GOTO = Pattern.compile("^goto(?:/16|/32)?\\s+(:\\S+)$");

    private final List<String> packageRoots;
    private final List<File> files;
    private final List<Occurrence> occurrences = new ArrayList<>();

    private SmaliScan(List<String> packageRoots, List<File> files) {
        this.packageRoots = packageRoots;
        this.files = files;
    }

    public static SmaliScan scan(String decodedPath, String applicationId) {
        return scan(decodedPath, applicationId, ConsumerRules.defaults());
    }

    public static SmaliScan scan(String decodedPath, String applicationId, ConsumerRules rules) {
        List<String> roots = AppCode.packageRoots(decodedPath, applicationId);
        SmaliScan scan = new SmaliScan(roots, AppCode.smaliFiles(decodedPath, roots));
        java.nio.file.Path base = Paths.get(decodedPath).toAbsolutePath();
        for (File file : scan.files) {
            String relative = base.relativize(file.toPath().toAbsolutePath()).toString().replace('\\', '/');
            try {
                scan.scanFile(Files.readAllLines(file.toPath(), StandardCharsets.UTF_8), relative, rules);
            } catch (IOException e) {
                // Unreadable file: skip it.
            }
        }
        return scan;
    }

    /** Every literal of the app's code, in file and line order. */
    public List<Occurrence> occurrences() {
        return Collections.unmodifiableList(occurrences);
    }

    /** The smali files of the app (all of them, with or without literals). */
    public List<File> files() {
        return Collections.unmodifiableList(files);
    }

    /** The package roots the app's code was found under. */
    public List<String> packageRoots() {
        return Collections.unmodifiableList(packageRoots);
    }

    // ------------------------------------------------------------------ scanning

    private void scanFile(List<String> lines, String relativePath, ConsumerRules rules) {
        String className = classNameOf(lines, relativePath);
        int i = 0;
        while (i < lines.size()) {
            String t = lines.get(i).trim();
            if (!t.startsWith(".method ")) {
                i++;
                continue;
            }
            int end = i + 1;
            while (end < lines.size() && !lines.get(end).trim().equals(".end method")) {
                end++;
            }
            String method = methodNameOf(t);
            for (int k = i + 1; k < end; k++) {
                Matcher m = CONST_STRING.matcher(lines.get(k).trim());
                if (!m.matches()) {
                    continue;
                }
                Object[] use = resolve(lines, i + 1, k + 1, end, m.group(1), rules);
                occurrences.add(new Occurrence(relativePath, k + 1, className, method, m.group(1),
                        SmaliText.unescape(m.group(2)), (Consumer) use[0], (String) use[1], occurrences.size()));
            }
            i = end + 1;
        }
    }

    private static String classNameOf(List<String> lines, String relativePath) {
        for (String line : lines) {
            String t = line.trim();
            if (t.startsWith(".class ")) {
                int l = t.lastIndexOf(" L");
                if (l >= 0 && t.endsWith(";")) {
                    return t.substring(l + 2, t.length() - 1).replace('/', '.');
                }
                break;
            }
        }
        // no .class line: derive it from the path below the dex folder
        int slash = relativePath.indexOf('/');
        String p = slash >= 0 ? relativePath.substring(slash + 1) : relativePath;
        return p.replace(".smali", "").replace('/', '.');
    }

    /** {@code .method public static final foo(I)V} gives {@code foo}. */
    private static String methodNameOf(String methodLine) {
        int paren = methodLine.indexOf('(');
        String head = paren >= 0 ? methodLine.substring(0, paren) : methodLine;
        int space = head.lastIndexOf(' ');
        return space >= 0 ? head.substring(space + 1) : head;
    }

    /**
     * Follows {@code register} from line index {@code from} to the end of the method (whose body is
     * the lines {@code start} to {@code end}) and returns {consumer, via}.
     */
    private Object[] resolve(List<String> lines, int start, int from, int end, String register, ConsumerRules rules) {
        Set<String> value = new HashSet<>();      // registers that hold the text, or a text built from it
        Set<String> builders = new HashSet<>();   // registers that hold a builder the text went into
        value.add(register);
        int steps = 0;
        for (int i = from; i < end && steps < MAX_STEPS; i++) {
            String t = lines.get(i).trim();
            if (t.isEmpty() || t.charAt(0) == '.' || t.charAt(0) == ':' || t.charAt(0) == '#') {
                continue;   // directives (.line, .local, .catch), labels, comments
            }
            steps++;
            Matcher inv = INVOKE.matcher(t);
            if (inv.matches()) {
                List<String> args = registers(inv.group(2), inv.group(1) != null);
                boolean takesValue = intersects(args, value);
                boolean takesBuilder = intersects(args, builders);
                if (!takesValue && !takesBuilder) {
                    continue;
                }
                String callee = inv.group(3);
                ConsumerRules.Kind kind = rules.classify(callee);
                if (kind == ConsumerRules.Kind.BUILDER) {
                    if (takesValue && !args.isEmpty()) {
                        builders.add(args.get(0));          // the text goes into the receiver
                    }
                    int result = moveResultLine(lines, i + 1, end);
                    if (result >= 0) {                      // append() returns the builder: another name for it
                        String r = firstRegister(lines.get(result).trim());
                        value.remove(r);
                        builders.add(r);
                        i = result;
                    }
                    continue;
                }
                if (kind == ConsumerRules.Kind.PASSTHROUGH) {
                    int result = moveResultLine(lines, i + 1, end);
                    if (result >= 0) {                      // the returned text carries ours
                        String r = firstRegister(lines.get(result).trim());
                        builders.remove(r);
                        value.add(r);
                        i = result;
                    }
                    continue;
                }
                if (kind != null) {
                    return use(Consumer.valueOf(kind.name()), callee);
                }
                String owner = callee.startsWith("L") && callee.contains(";") ? callee.substring(1, callee.indexOf(';')) : callee;
                return use(AppCode.isUnder(packageRoots, owner) ? Consumer.APP_CALL : Consumer.LIBRARY_CALL, callee);
            }
            Matcher filled = FILLED_ARRAY.matcher(t);
            if (filled.find()) {
                if (intersects(registers(filled.group(2), filled.group(1) != null), value)) {
                    return use(Consumer.ARRAY, "");
                }
                continue;
            }
            Matcher op = OPERANDS.matcher(t);
            if (!op.find()) {
                Matcher jump = GOTO.matcher(t);
                if (jump.matches()) {                       // the code goes on at the label (the step limit stops a loop)
                    int target = labelLine(lines, start, end, jump.group(1));
                    if (target < 0) {
                        break;
                    }
                    i = target;
                    continue;
                }
                if (t.startsWith("return")) {
                    break;                                  // return-void: this path of the method ends here
                }
                continue;
            }
            String opcode = op.group(1);
            String first = op.group(2);
            String second = op.group(3);
            if (opcode.startsWith("move-object") || opcode.equals("move") || opcode.startsWith("move/")) {
                if (second != null && value.contains(second)) {
                    builders.remove(first);
                    value.add(first);
                } else if (second != null && builders.contains(second)) {
                    value.remove(first);
                    builders.add(first);
                } else {
                    value.remove(first);
                    builders.remove(first);
                }
            } else if (opcode.startsWith("iput") || opcode.startsWith("sput")) {
                if (value.contains(first) || builders.contains(first)) {
                    return use(Consumer.FIELD, t.substring(t.lastIndexOf(' ') + 1));
                }
            } else if (opcode.startsWith("return")) {
                if (value.contains(first) || builders.contains(first)) {
                    return use(Consumer.RETURN, "");
                }
                break;
            } else if (opcode.startsWith("aput")) {
                if (value.contains(first)) {
                    return use(Consumer.ARRAY, "");
                }
            } else if (opcode.startsWith("throw")) {
                break;
            } else if (opcode.startsWith("if-") || opcode.startsWith("monitor") || opcode.equals("check-cast")
                    || opcode.contains("switch") || opcode.startsWith("fill-array-data")) {
                // reads its operand: nothing to follow
            } else {
                // any other instruction writes its first operand: that register no longer holds the text
                value.remove(first);
                builders.remove(first);
            }
            if (value.isEmpty() && builders.isEmpty()) {
                return use(Consumer.UNUSED, "");
            }
        }
        return use(builders.isEmpty() ? Consumer.UNUSED : Consumer.CONCATENATION, "");
    }

    private static Object[] use(Consumer consumer, String via) {
        // keep class and method, drop the descriptor: it is long and adds nothing to a report
        int paren = via.indexOf('(');
        return new Object[] {consumer, paren > 0 ? via.substring(0, paren) : via};
    }

    private static int labelLine(List<String> lines, int start, int end, String label) {
        for (int i = start; i < end; i++) {
            if (lines.get(i).trim().equals(label)) {
                return i;
            }
        }
        return -1;
    }

    /** Index of the {@code move-result-object} that immediately follows a call, or -1. */
    private static int moveResultLine(List<String> lines, int from, int end) {
        for (int i = from; i < end; i++) {
            String t = lines.get(i).trim();
            if (t.isEmpty() || t.charAt(0) == '.' || t.charAt(0) == ':' || t.charAt(0) == '#') {
                continue;
            }
            return t.startsWith("move-result-object ") ? i : -1;
        }
        return -1;
    }

    private static String firstRegister(String instruction) {
        Matcher m = OPERANDS.matcher(instruction);
        return m.find() ? m.group(2) : "";
    }

    private static List<String> registers(String list, boolean range) {
        List<String> out = new ArrayList<>();
        String args = list.trim();
        if (args.isEmpty()) {
            return out;
        }
        if (range) {
            Matcher m = RANGE.matcher(args);
            if (m.find() && m.group(1).equals(m.group(3))) {
                int a = Integer.parseInt(m.group(2));
                int b = Integer.parseInt(m.group(4));
                for (int k = a; k <= b && k - a < 256; k++) {
                    out.add(m.group(1) + k);
                }
            }
            return out;
        }
        for (String a : args.split(",")) {
            out.add(a.trim());
        }
        return out;
    }

    private static boolean intersects(List<String> args, Set<String> registers) {
        for (String a : args) {
            if (registers.contains(a)) {
                return true;
            }
        }
        return false;
    }
}
